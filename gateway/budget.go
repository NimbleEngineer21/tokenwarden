package gateway

import (
	"context"
	"encoding/json"
	"errors"
	"log/slog"
	"math"
	"net/http"
	"strconv"
	"time"

	"github.com/NimbleEngineer21/tokenwarden/audit"
	"github.com/NimbleEngineer21/tokenwarden/internal/anthropic"
	"github.com/NimbleEngineer21/tokenwarden/limit"
)

// topUpChunk is the most output tokens that one reserve or top-up holds for
// a stream. It is also the overspend bound of one stream.
const topUpChunk = 512

// Messages of the budget errors.
const (
	errMsgExceeded    = "the team's token budget for this window is used up"
	errMsgNoBudget    = "the team has no token budget"
	errMsgConcurrency = "the team has too many requests in flight"
	errMsgUnavailable = "the token budget service is unavailable"
)

// budget is the hold on a team's token budget for one request.
type budget struct {
	res limit.Reservation
	est limit.Estimator
	// input is the guess of the request's input tokens.
	input int64
	// ceiling is input plus max_tokens: the most that the reply can use,
	// so no top-up goes past it.
	ceiling int64
	// outBytes counts the generated bytes that the client has received.
	outBytes int64
}

// reserve holds the request's first tokens. On failure it sends the error
// reply, notes it in ev, and returns nil.
func (g *gateway) reserve(ctx context.Context, w http.ResponseWriter, ev *audit.Event, body []byte, stream bool, log *slog.Logger) *budget {
	var p struct {
		MaxTokens *int64 `json:"max_tokens"`
	}
	if json.Unmarshal(body, &p) != nil || p.MaxTokens == nil || *p.MaxTokens <= 0 {
		fail(w, ev, audit.OutcomeInvalid, http.StatusBadRequest, anthropic.ErrInvalidRequest, "max_tokens must be a positive integer")
		return nil
	}
	input := max(g.est.InputTokens(body), 1)
	b := &budget{est: g.est, input: input, ceiling: satAdd(input, *p.MaxTokens)}
	first := b.ceiling
	if stream {
		first = satAdd(input, min(topUpChunk, *p.MaxTokens))
	}
	res, err := g.limiter.Reserve(ctx, ev.Team, first)
	if err == nil {
		b.res = res
		return b
	}
	var ee *limit.ExceededError
	switch {
	case errors.Is(err, limit.ErrBudgetExceeded):
		g.metrics.denials.WithLabelValues(ev.Team, "reserve").Inc()
		if errors.As(err, &ee) {
			secs := math.Ceil(time.Until(ee.Window.End()).Seconds())
			w.Header().Set("Retry-After", strconv.FormatFloat(max(secs, 1), 'f', 0, 64))
		}
		fail(w, ev, audit.OutcomeBudgetExceeded, http.StatusTooManyRequests, anthropic.ErrRateLimit, errMsgExceeded)
	case errors.Is(err, limit.ErrConcurrencyExceeded):
		// No Retry-After: nothing tells when a slot frees up, and clients
		// back off on a 429 without one.
		g.metrics.denials.WithLabelValues(ev.Team, "concurrency").Inc()
		fail(w, ev, audit.OutcomeBudgetExceeded, http.StatusTooManyRequests, anthropic.ErrRateLimit, errMsgConcurrency)
	case errors.Is(err, limit.ErrNoBudget):
		g.metrics.denials.WithLabelValues(ev.Team, "reserve").Inc()
		fail(w, ev, audit.OutcomeBudgetExceeded, http.StatusForbidden, anthropic.ErrPermission, errMsgNoBudget)
	case ctx.Err() != nil:
		ev.Outcome = audit.OutcomeCanceled
	default:
		log.ErrorContext(ctx, "reserve failed", "err", err)
		fail(w, ev, audit.OutcomeGatewayError, http.StatusServiceUnavailable, anthropic.ErrAPI, errMsgUnavailable)
	}
	return nil
}

// ensure tops up the reservation, one chunk at a time, until it covers n
// more generated bytes. It counts the bytes only when they fit, since the
// caller sends them only then. At the ceiling it holds no more: the
// estimate is past what the upstream can send, so the settle corrects it.
func (b *budget) ensure(ctx context.Context, m *metrics, n int64) error {
	need := satAdd(b.input, b.est.OutputTokens(b.outBytes+n))
	for held := b.res.Reserved(); held < need && held < b.ceiling; held = b.res.Reserved() {
		err := b.res.TopUp(ctx, min(topUpChunk, b.ceiling-held))
		switch {
		case err == nil:
			m.topUps.WithLabelValues("ok").Inc()
			continue
		case errors.Is(err, limit.ErrBudgetExceeded):
			m.topUps.WithLabelValues("exceeded").Inc()
		default:
			m.topUps.WithLabelValues("error").Inc()
		}
		return err
	}
	b.outBytes += n
	return nil
}

// used returns the tokens to charge for the request. A reply that did not
// start costs nothing. A whole reply costs what the upstream reported. A
// reply that ended early costs at least the gateway's own estimate, since
// the upstream report of a cut-off stream can lack the output so far.
func (b *budget) used(ev *audit.Event) int64 {
	if ev.Status < 200 || ev.Status >= 300 {
		return 0
	}
	u := ev.Usage
	in := u.InputTokens + u.CacheCreationInputTokens + u.CacheReadInputTokens
	if ev.Outcome == audit.OutcomeOK {
		if in+u.OutputTokens == 0 {
			// The usage could not be read; charge the hold.
			return b.res.Reserved()
		}
		return in + u.OutputTokens
	}
	if in == 0 {
		in = b.input
	}
	return satAdd(in, max(u.OutputTokens, b.est.OutputTokens(b.outBytes)))
}

// settle ends the reservation. It runs after the reply, so it can only log
// a failure; the tokens then stay held.
func (b *budget) settle(ctx context.Context, ev *audit.Event, log *slog.Logger) {
	if err := b.res.Settle(context.WithoutCancel(ctx), b.used(ev)); err != nil {
		log.ErrorContext(ctx, "settle failed", "err", err)
	}
}

// satAdd adds two non-negative counts and stops at the int64 maximum, since
// max_tokens comes from the client.
func satAdd(a, b int64) int64 {
	if b > math.MaxInt64-a {
		return math.MaxInt64
	}
	return a + b
}
